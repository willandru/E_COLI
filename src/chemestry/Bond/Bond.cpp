#include "Bond.h"

namespace Chemistry
{

// ============================================================
// Constructor
// ============================================================

Bond::Bond(
    Atom& atomA,
    Atom& atomB,
    BondType type
)
    :
    m_atomA(&atomA),
    m_atomB(&atomB),
    m_type(type)
{
}


// ============================================================
// Atom A
// ============================================================

const Atom& Bond::getAtomA() const
{
    return *m_atomA;
}


// ============================================================
// Atom B
// ============================================================

const Atom& Bond::getAtomB() const
{
    return *m_atomB;
}


// ============================================================
// Bond type
// ============================================================

BondType Bond::getType() const
{
    return m_type;
}

}