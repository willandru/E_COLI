#pragma once

#include "BondType.h"

namespace Chemistry
{

// ============================================================
// Datos físicos de un tipo de enlace
// ============================================================

struct BondData
{
    // ========================================================
    // Tipo
    // ========================================================

    BondType type;


    // ========================================================
    // Orden del enlace
    // ========================================================
    //
    // Single -> 1
    // Double -> 2
    // Triple -> 3
    //
    // ========================================================

    int order;


    // ========================================================
    // Longitud típica del enlace
    //
    // Unidad: Å
    // ========================================================

    float typicalLength;


    // ========================================================
    // Energía aproximada
    //
    // Unidad: kJ/mol
    // ========================================================

    float typicalEnergy;
};


// ============================================================
// Datos generales de los tipos de enlace
// ============================================================

const BondData& getBondData(
    BondType type
);

}