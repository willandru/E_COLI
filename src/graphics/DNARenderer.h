#pragma once

#include "Shader.h"
#include "Camera.h"
#include "Window.h"
#include "DNA.h"

#include <glm/glm.hpp>

#include <vector>


class DNARenderer
{
public:

    // ========================================================
    // Constructor
    // ========================================================

    DNARenderer(
        const DNA& dna
    );


    // ========================================================
    // Destructor
    // ========================================================

    ~DNARenderer();


    // ========================================================
    // Render
    // ========================================================

    void render(
        const Camera& camera,
        const Window& window
    );


private:

    // ========================================================
    // Geometría base
    // ========================================================

    void createGeometry();


    // ========================================================
    // Crear buffer inicial
    // ========================================================

    void createInstances(
        const DNA& dna
    );


    // ========================================================
    // Actualizar representación
    // ========================================================

    void updateInstances(
        const Camera& camera
    );


    // ========================================================
    // Determinar LOD
    // ========================================================

    unsigned int calculateLOD(
        float distance
    ) const;


private:

    // ========================================================
    // OpenGL
    // ========================================================

    unsigned int m_VAO;

    unsigned int m_VBO;

    unsigned int m_instanceVBO;


    // ========================================================
    // Número de instancias actualmente renderizadas
    // ========================================================

    unsigned int m_instanceCount;


    // ========================================================
    // Total de bases del genoma
    // ========================================================

    unsigned int m_totalBases;


    // ========================================================
    // Bases representadas por instancia
    // ========================================================

    unsigned int m_baseStep;


    // ========================================================
    // Última posición utilizada para actualizar
    // ========================================================

    glm::vec3 m_lastCameraPosition;


    // ========================================================
    // Último LOD utilizado
    // ========================================================

    unsigned int m_lastLOD;


    // ========================================================
    // Shader
    // ========================================================

    Shader m_shader;


    // ========================================================
    // Referencia al DNA
    // ========================================================

    const DNA& m_dna;
};